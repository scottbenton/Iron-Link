#!/usr/bin/env node
// Writes src/components/worlds/categories/bundledGameIcons.ts: the Game Icons
// the built-in world templates and map location types use, so they draw
// without loading the whole lazy icon set.
//
//   npm run generate:bundled-game-icons
//
// Run it after changing supabase/world-defaults.json or an icon in the
// sources below. bundledGameIcons.test.ts fails while the file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const icons = require("@iconify-json/game-icons/icons.json");

// Sources whose "Gi*" string literals are default icons.
const SOURCE_FILES = [
  "src/lib/worldMap/locationTypeIcons.ts",
  "src/components/worlds/categories/WorldFieldKindPreview.tsx",
];

const keys = new Set();
JSON.parse(
  readFileSync(resolve(root, "supabase/world-defaults.json"), "utf8"),
  (_, value) => {
    if (typeof value === "string" && /^Gi[A-Z0-9]\w*$/.test(value))
      keys.add(value);
    return value;
  },
);
for (const file of SOURCE_FILES) {
  const source = readFileSync(resolve(root, file), "utf8");
  for (const [, key] of source.matchAll(/"(Gi[A-Z0-9]\w*)"/g)) keys.add(key);
}

// Mirrors getGameIconKey in gameIconKeys.ts, which the test checks.
const KEY_EXCEPTIONS = { ak47u: "GiAk47U", h2o: "GiH2O", mp5k: "GiMp5K" };
const toKey = (name) =>
  KEY_EXCEPTIONS[name] ??
  "Gi" +
    name
      .split("-")
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join("");
const nameByKey = new Map(
  Object.keys(icons.icons).map((name) => [toKey(name), name]),
);

const entries = [...keys].sort().map((key) => {
  const name = nameByKey.get(key);
  if (!name) throw new Error(`${key} is not a Game Icon`);
  const paths = Array.from(
    icons.icons[name].body.matchAll(/\sd="([^"]*)"/g),
    (m) => m[1],
  );
  return `  ${key}: ${JSON.stringify(paths)},`;
});

writeFileSync(
  resolve(root, "src/components/worlds/categories/bundledGameIcons.ts"),
  `// Generated by scripts/generate-bundled-game-icons.mjs; do not edit by hand.
// The Game Icons the built-in world templates and location types use, drawn
// without loading the whole set.
import type { CategoryIconSet } from "./categoryIcons";

export const BUNDLED_GAME_ICONS: CategoryIconSet = {
${entries.join("\n")}
};
`,
);
console.log(`Bundled ${entries.length} icons`);
