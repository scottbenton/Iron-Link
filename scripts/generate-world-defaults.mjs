#!/usr/bin/env node
// Writes supabase/world-defaults.json and supabase/world-defaults.md from the
// shared world templates in a migrated local database.
//
//   npm run generate:world-defaults
//
// DATABASE_URL defaults to the local Supabase database. PSQL overrides the
// psql command, for example "docker exec -i <db container> psql".
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const databaseUrl =
  process.env.DATABASE_URL ??
  "postgresql://postgres:postgres@127.0.0.1:54322/postgres";
const [psql, ...psqlArgs] = (process.env.PSQL ?? "psql").split(/\s+/);

const query = `select coalesce(json_agg(json_build_object('setting_key', setting_key,
  'configuration', configuration) order by setting_key), '[]') from public.world_templates`;
const result = spawnSync(
  psql,
  [
    ...psqlArgs,
    "-X",
    "-A",
    "-t",
    "-v",
    "ON_ERROR_STOP=1",
    "-d",
    databaseUrl,
    "-c",
    query,
  ],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);
if (result.error) throw result.error;
if (result.status !== 0) {
  process.stderr.write(result.stderr);
  process.exit(result.status ?? 1);
}

const rows = JSON.parse(result.stdout);
if (!Array.isArray(rows) || rows.length === 0) {
  throw new Error("No world templates found; is the database migrated?");
}

// Object keys are sorted so output never depends on jsonb key order. Arrays
// keep their stored order, which is meaningful (rules, options).
function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, sortKeys(value[key])]),
    );
  }
  return value;
}

const defaults = Object.fromEntries(
  rows
    .map((row) => [row.setting_key, sortKeys(row.configuration)])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
);
writeFileSync(
  resolve(root, "supabase/world-defaults.json"),
  `${JSON.stringify(defaults, null, 2)}\n`,
);

const bySortOrder = (a, b) =>
  a.sort_order - b.sort_order || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
const operators = {
  equals: "=",
  notEquals: "!=",
  contains: "contains",
  notContains: "does not contain",
  isEmpty: "is empty",
  isNotEmpty: "is not empty",
};
const quote = (value) => JSON.stringify(value);
const oracle = (binding) =>
  binding && binding.oracleId ? `\`${binding.oracleId}\`` : null;

function kind(field, categoryNames) {
  const configuration = field.configuration;
  if (field.type === "text")
    return configuration.fullWidth ? "Text, full width" : "Text";
  if (field.type === "richText") return "Long text";
  if (field.type !== "select") return `Unknown (${field.type})`;
  const count = configuration.multiple ? "multiple" : "single";
  if (configuration.targetCategoryId) {
    const target =
      categoryNames.get(configuration.targetCategoryId) ??
      configuration.targetCategoryId;
    return `Linked entry → ${target}, ${count}`;
  }
  return `Option list, ${count}, ${configuration.allowOther ? "allows other values" : "strict"}`;
}

function describeCondition(condition, labels) {
  const label = labels.get(condition.fieldId) ?? condition.fieldId;
  const test = [label, operators[condition.operator] ?? condition.operator];
  if ("value" in condition) test.push(quote(condition.value));
  const text = test.join(" ");
  if (condition.source !== "ancestor") return text;
  const selector =
    labels.get(condition.ancestor.fieldId) ?? condition.ancestor.fieldId;
  return `nearest ancestor with ${selector} = ${quote(condition.ancestor.value)}: ${text}`;
}

function describeRule(rule, labels) {
  const effects = [];
  if ("visible" in rule) effects.push(rule.visible ? "show" : "hide");
  if (rule.label) effects.push(`label ${quote(rule.label)}`);
  if (rule.helpText) effects.push("help text");
  if (oracle(rule.binding)) effects.push(`oracle ${oracle(rule.binding)}`);
  const conditions = rule.conditions
    .map((condition) => describeCondition(condition, labels))
    .join(" and ");
  return `when ${conditions} → ${effects.join(", ") || "no change"}`;
}

const lines = [
  "<!-- Generated by scripts/generate-world-defaults.mjs from public.world_templates. -->",
  "<!-- Do not edit. Regenerate with `npm run generate:world-defaults` against a migrated local database. -->",
  "",
  "# World defaults",
  "",
  "Shared category and field defaults for each setting. Inherited worlds read these",
  "rows until their first configuration edit copies them.",
];
for (const [settingKey, configuration] of Object.entries(defaults)) {
  lines.push("", `## ${settingKey}`);
  const categories = [...configuration.categories].sort(bySortOrder);
  const categoryNames = new Map(categories.map((c) => [c.id, c.name]));
  for (const category of categories) {
    const fields = [...category.fields].sort(bySortOrder);
    const labels = new Map(fields.map((f) => [f.id, f.label]));
    const capabilities = [
      category.supports_hierarchy && "hierarchy",
      category.supports_map && "map",
      category.supports_bonds && "bonds",
    ].filter(Boolean);
    lines.push("", `### ${category.name} (\`${category.key}\`)`, "");
    lines.push(
      `Supports: ${capabilities.join(", ") || "none"}. Subtitle: ${
        labels.get(category.subtitle_field_definition_id) ?? "none"
      }.`,
    );
    if (fields.length === 0) lines.push("", "No fields.");
    else lines.push("");
    for (const field of fields) {
      const details = [kind(field, categoryNames)];
      if (field.gm_only) details.push("Guide-only");
      if (!field.configuration.visible)
        details.push("hidden unless a rule shows it");
      if (oracle(field.binding))
        details.push(`oracle ${oracle(field.binding)}`);
      lines.push(
        `- **${field.label}** (\`${field.key}\`): ${details.join("; ")}`,
      );
      if (field.configuration.suggestions.length > 0) {
        lines.push(
          `  - Options: ${field.configuration.suggestions.map(quote).join(", ")}`,
        );
      }
      for (const rule of field.configuration.rules) {
        lines.push(`  - ${describeRule(rule, labels)}`);
      }
    }
  }
}
writeFileSync(
  resolve(root, "supabase/world-defaults.md"),
  `${lines.join("\n")}\n`,
);
