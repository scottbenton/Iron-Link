// Regenerate the trusted SQL catalog whenever static TypeScript defaults change.
// Pass --check in CI to detect client/server catalog drift.
import { build } from "esbuild";
import { v5 as uuid } from "uuid";
import { mkdtemp, rm, readFile, writeFile, readdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root = fileURLToPath(new URL("../../", import.meta.url));
const temporary = await mkdtemp(path.join(tmpdir(), "iron-link-static-world-"));
try {
  const outfile = path.join(temporary, "templates.mjs");
  await build({ absWorkingDir: root, entryPoints: ["src/lib/worldTemplates.ts"], tsconfig: "tsconfig.app.json", bundle: true, platform: "node", format: "esm", outfile });
  const { buildWorldTemplate } = await import(pathToFileURL(outfile));
  const namespace = "00000000-0000-4000-8000-000000000000";
  const settings = [null,"world:classic/ironlands","world:starforged/forge","world:sundered_isles/sundered_isles","world:elegy/santa_maria"];
  const catalog = Object.fromEntries(settings.map(setting => [setting ?? "blank", buildWorldTemplate(setting, namespace)]));
  const sql = `-- Generated by supabase/tests/generate-static-world-catalog.mjs. Do not hand edit.
-- Release defaults are immutable function source, never per-world database rows.
create or replace function public.w4_static_world_template(p_world_id uuid, p_setting_key text) returns jsonb
language plpgsql immutable set search_path = '' as $$
declare catalog jsonb := $catalog$${JSON.stringify(catalog)}$catalog$::jsonb;
  template jsonb; category jsonb; field jsonb; rewritten text; category_key text;
begin
  template := coalesce(catalog->p_setting_key,catalog->'blank');
  rewritten := template::text;
  for category in select value from jsonb_array_elements(template->'categories') loop
    category_key := case category->>'id' ${['locations','npcs','lore'].map(key => `when '${uuid('category:'+key,namespace)}' then '${key}'`).join(' ')} end;
    if category_key is null then raise exception 'Unknown static category identity'; end if;
    rewritten := replace(rewritten, category->>'id', extensions.uuid_generate_v5(p_world_id,'category:' || category_key)::text);
    for field in select value from jsonb_array_elements(category->'fields') loop
      rewritten := replace(rewritten, field->>'id', extensions.uuid_generate_v5(p_world_id,'field:' || category_key || ':' || (field->>'key'))::text);
    end loop;
  end loop;
  return rewritten::jsonb;
end $$;
revoke all on function public.w4_static_world_template(uuid,text) from public, anon, authenticated;
-- On later catalog releases, synchronize inherited value visibility through the
-- trusted resolver. Missing/deleted definitions fail the migration closed.
do $refresh$
begin
  if to_regprocedure('public.w4_effective_categories(uuid)') is not null then
    update public.world_entry_field_values v set gm_only = v.gm_only
      from public.worlds w where w.id = v.world_id and not w.configuration_customized;
  end if;
end $refresh$;
`;
  const migrations = path.join(root, "supabase/migrations");
  const outputIndex = process.argv.indexOf("--output");
  const latest = (await readdir(migrations)).filter(name => name.endsWith("_world_static_catalog.sql")).sort().at(-1);
  const target = outputIndex >= 0
    ? path.resolve(root, process.argv[outputIndex + 1])
    : path.join(migrations, latest ?? "20260926010000_world_static_catalog.sql");
  if (process.argv.includes("--check")) {
    if (await readFile(target,"utf8") !== sql) throw new Error("Static world catalog is out of date; run node supabase/tests/generate-static-world-catalog.mjs");
  } else await writeFile(target, sql);
} finally { await rm(temporary, {recursive:true,force:true}); }
